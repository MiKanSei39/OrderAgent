import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

test('桌面界面与菜单筛选', async ({ page }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '今天，想吃点什么？' })).toBeVisible()
  await expect(page.locator('.live-status')).toContainText('基础服务可用')
  await mkdir('../artifacts', { recursive: true })
  await page.screenshot({ path: '../artifacts/ui-desktop.png', fullPage: true })
  await page.getByRole('button', { name: /当季菜单/ }).click()
  await expect(page.locator('.dish-card')).toHaveCount(5)
  await page.getByLabel('只看素食').check()
  await expect(page.locator('.dish-card')).toHaveCount(2)
  await page.getByLabel('只看不辣').check()
  await expect(page.locator('.dish-card')).toHaveCount(2)
  await page.getByLabel('搜索菜单').fill('西兰花')
  await expect(page.locator('.dish-card')).toHaveCount(1)
  await expect(page.locator('.dish-card')).toContainText('蒜蓉西兰花')
  expect(errors).toEqual([])
})

test('FAQ建议、SSE回复和刷新后的历史', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('输入点餐问题').fill('电话')
  await expect(page.locator('.faq-suggestions')).toBeVisible()
  await page.getByLabel('发送消息').click()
  await expect(page.locator('.message.assistant')).toContainText('021-12345678')
  await page.reload()
  await expect(page.locator('.message.assistant')).toContainText('021-12345678')
  await page.getByRole('button', { name: /新会话/ }).click()
  await expect(page.locator('.message')).toHaveCount(0)
})

test('表单草稿、二次确认和订单持久化', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /我的预订/ }).click()
  const date = new Date(Date.now() + 3 * 86400000).toISOString().slice(0, 10)
  await page.getByLabel(/到店时间/).fill(date + 'T18:30')
  await page.getByLabel('到店总人数（含儿童）').fill('3')
  await page.getByLabel('其中0—5岁儿童').fill('1')
  await page.getByRole('button', { name: '生成预订确认单 →' }).click()
  await expect(page.locator('.confirmation-card')).toContainText('尚未下单')
  await expect(page.locator('.order-item')).toHaveCount(0)
  await page.getByRole('button', { name: '信息无误，确认预订' }).click()
  await expect(page.locator('.order-item')).toHaveCount(1)
  await expect(page.locator('.confirmation-card')).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: /我的预订/ }).click()
  await expect(page.locator('.order-item')).toHaveCount(1)
  await page.screenshot({ path: '../artifacts/ui-reservation.png', fullPage: true })
})

test('手机界面不横向溢出', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByLabel('发送消息')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: '../artifacts/ui-mobile.png', fullPage: true })
  await page.getByRole('button', { name: /当季菜单/ }).click()
  await expect(page.locator('.dish-card')).toHaveCount(5)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})
